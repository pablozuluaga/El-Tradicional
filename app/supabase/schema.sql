-- =============================================================================
-- El Tradicional · Supabase schema (settings, orders, chat, RLS, RPCs, realtime)
--
-- Setup, once per project:
--   1. Authentication → Sign In / Providers → turn on "Allow anonymous sign-ins"
--      (customers get a device-bound identity without a password).
--   2. SQL editor → run this whole file. It is safe to re-run.
--   3. Authentication → Users → "Add user" for the owner (email + password), then:
--        insert into public.owners (user_id)
--        select id from auth.users where email = 'CORREO-DEL-DUENO';
--   4. In the app, set VITE_SUPABASE_URL and VITE_SUPABASE_PUBLISHABLE_KEY (or VITE_SUPABASE_ANON_KEY) and rebuild.
--
-- Security model: customers and the owner can READ what row-level security allows,
-- but every WRITE except owner settings goes through the security-definer functions below.
-- Known limit: dish prices and barrio fees are still computed in the app; the owner sees
-- them on every order before accepting it.
-- =============================================================================

-- ---------------------------------------------------------------- settings --
create table if not exists public.settings (
  id             smallint primary key default 1 check (id = 1),
  store_open     boolean not null default true,
  plato_dia      text check (plato_dia in ('lunes','martes','miercoles','jueves','viernes','sabado','domingo')),
  day_off        jsonb not null default '{}'::jsonb,
  sold_proteins  jsonb not null default '{}'::jsonb,
  sold_dishes    jsonb not null default '{}'::jsonb,
  juices         jsonb not null default '[{"id":"guandolo","label":"Guandolo","out":false},{"id":"jugo","label":"Jugo","out":false}]'::jsonb,
  desc_overrides jsonb not null default '{}'::jsonb,
  day_soups      jsonb not null default '{}'::jsonb,
  custom_dishes  jsonb not null default '[]'::jsonb,
  day_proteins   jsonb not null default '{}'::jsonb,
  sold_flavors   jsonb not null default '{}'::jsonb,
  dessert_flavors jsonb,
  juice_flavors  jsonb not null default '[]'::jsonb,
  dish_on        jsonb not null default '{}'::jsonb,
  updated_at     timestamptz not null default now()
);
