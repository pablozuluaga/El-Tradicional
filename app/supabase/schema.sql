alter table public.settings add column if not exists day_soups     jsonb not null default '{}'::jsonb;
alter table public.settings add column if not exists custom_dishes jsonb not null default '[]'::jsonb;
alter table public.settings add column if not exists day_proteins  jsonb not null default '{}'::jsonb;
alter table public.settings add column if not exists sold_flavors  jsonb not null default '{}'::jsonb;
alter table public.settings add column if not exists dessert_flavors jsonb;
alter table public.settings add column if not exists juice_flavors jsonb not null default '[]'::jsonb;
alter table public.settings add column if not exists dish_on       jsonb not null default '{}'::jsonb;
insert into public.settings (id) values (1) on conflict (id) do nothing;

create or replace function public.touch_updated_at() returns trigger
language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;

drop trigger if exists settings_touch on public.settings;
create trigger settings_touch before update on public.settings
  for each row execute function public.touch_updated_at();

-- ------------------------------------------------------------------ owners --
create table if not exists public.owners (
  user_id uuid primary key references auth.users (id) on delete cascade
);

create or replace function public.is_owner() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.owners where user_id = (select auth.uid()));
$$;

-- ------------------------------------------------------------------ orders --
create table if not exists public.orders (
  num            bigint generated by default as identity (start with 1043) primary key,
  customer_id    uuid not null,
  name           text not null check (char_length(name) between 1 and 150),
  email          text not null check (char_length(email) between 3 and 200),
  phone          text not null default '—' check (char_length(phone) <= 40),
  origin         text not null check (origin in ('domicilio','recoger')),
  zone_id        text,
  zone_label     text,
  address        text not null default '' check (char_length(address) <= 300),
  address_notes  text not null default '' check (char_length(address_notes) <= 300),
  items          text not null check (char_length(items) <= 4000),
  items_list     jsonb not null default '[]'::jsonb,
  lines          jsonb not null default '[]'::jsonb,
  subtotal       integer not null check (subtotal >= 0),
  delivery       integer not null default 0 check (delivery >= 0),
  delivery_pending boolean not null default false,
  total          integer not null check (total >= 0), -- always subtotal + delivery: full price
  pay            text not null check (char_length(pay) <= 80),
  status         text not null default 'nuevo' check (status in ('nuevo','aceptado','camino','listo','rechazado')),
  reject_reason  text check (char_length(reject_reason) <= 200),
  rated          boolean not null default false,
  review_stars   smallint check (review_stars between 1 and 5),
  review_comment text check (char_length(review_comment) <= 500),
  client_seen_id bigint not null default 0,
  owner_seen_id  bigint not null default 0,
  created_at     timestamptz not null default now()
);
-- barrio "Otro": the owner sets the delivery fee afterwards (added after the first release)
alter table public.orders add column if not exists delivery_pending boolean not null default false;
create index if not exists orders_customer_idx on public.orders (customer_id);
create index if not exists orders_email_idx on public.orders (lower(email));
create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (status);

create table if not exists public.order_messages (
  id         bigint generated always as identity primary key,
  order_num  bigint not null references public.orders (num) on delete cascade,
  sender     text not null check (sender in ('cliente','dueno')),
  body       text not null check (char_length(body) between 1 and 1000),
  created_at timestamptz not null default now()
);
create index if not exists order_messages_order_idx on public.order_messages (order_num, id);

-- --------------------------------------------------------------------- RLS --
alter table public.settings       enable row level security;
alter table public.owners         enable row level security;
alter table public.orders         enable row level security;
alter table public.order_messages enable row level security;

drop policy if exists settings_read on public.settings;
create policy settings_read on public.settings for select to anon, authenticated using (true);
drop policy if exists settings_owner_update on public.settings;
create policy settings_owner_update on public.settings for update to authenticated
  using ((select public.is_owner())) with check ((select public.is_owner()));

drop policy if exists orders_read on public.orders;
create policy orders_read on public.orders for select to authenticated
  using (customer_id = (select auth.uid()) or (select public.is_owner()));

drop policy if exists order_messages_read on public.order_messages;
create policy order_messages_read on public.order_messages for select to authenticated
  using (
    (select public.is_owner())
    or exists (select 1 from public.orders o where o.num = order_num and o.customer_id = (select auth.uid()))
  );

-- Defense in depth: no direct writes besides the owner's settings update.
revoke all on public.owners from anon, authenticated;
revoke insert, update, delete, truncate on public.orders, public.order_messages from anon, authenticated;
revoke insert, delete, truncate on public.settings from anon, authenticated;
revoke update on public.settings from anon;

-- --------------------------------------------------------------- helpers --
create or replace function public._next_status(p_status text) returns text
language sql immutable set search_path = '' as $$
  -- 'camino' (en camino / listo para recoger) is the last step the owner marks; 'listo' remains for older orders
  select case p_status when 'nuevo' then 'aceptado' when 'aceptado' then 'camino' end;
$$;

create or replace function public._status_note(p_status text, p_origin text) returns text
language sql immutable set search_path = '' as $$
  select case
    when p_status = 'aceptado' then 'Pedido confirmado. Comenzamos con la preparación. 👨‍🍳'
    when p_status = 'camino' and p_origin = 'recoger' then 'Tu pedido está listo para recoger en el local. 🥡'
    when p_status = 'camino' then 'Tu pedido está en camino. 🛵'
    when p_status = 'listo' then 'Pedido entregado. ¡Buen provecho! 😋'
  end;
$$;

-- -------------------------------------------------------------------- RPCs --
create or replace function public.place_order(p jsonb) returns public.orders
language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  s public.settings;
  v_email text := trim(coalesce(p->>'email', ''));
  v_origin text := p->>'origin';
  v_sub int := (p->>'subtotal')::int;
  v_pending boolean := p->>'origin' = 'domicilio' and p->>'zone_id' = 'otro';
  v_delivery int := case when p->>'origin' = 'domicilio' and not coalesce(p->>'zone_id' = 'otro', false)
                         then coalesce((p->>'delivery')::int, 0) else 0 end;
  o public.orders;
  m_id bigint;
begin
  if uid is null then raise exception 'No autenticado.' using errcode = '28000'; end if;

  select * into s from public.settings where id = 1;
  if not s.store_open then raise exception 'La cocina está cerrada en este momento. Atendemos 11:30am – 4pm.'; end if;
  if char_length(trim(coalesce(p->>'name', ''))) = 0 then raise exception 'Falta tu nombre.'; end if;
  if v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' then raise exception 'Falta un correo válido.'; end if;
  if v_origin is null or v_origin not in ('domicilio', 'recoger') then raise exception 'Modo de entrega inválido.'; end if;
  if jsonb_typeof(p->'items_list') <> 'array' or jsonb_array_length(p->'items_list') = 0 then raise exception 'Tu carrito está vacío.'; end if;
  if jsonb_typeof(p->'lines') <> 'array' then raise exception 'Pedido inválido.'; end if;
  if v_sub is null or v_sub < 0 or v_delivery < 0 then raise exception 'Valores inválidos.'; end if;
  if v_origin = 'domicilio' then
    if coalesce(p->>'zone_id', '') = '' then raise exception 'Selecciona tu barrio.'; end if;
    if v_pending and char_length(trim(coalesce(p->>'zone_label', ''))) = 0 then raise exception 'Escribe el nombre de tu barrio.'; end if;
    if char_length(trim(coalesce(p->>'address', ''))) = 0 then raise exception 'Escribe la dirección de entrega.'; end if;
  end if;
  if exists (select 1 from jsonb_array_elements(p->'lines') l where coalesce((s.sold_dishes ->> (l->>'dishId'))::boolean, false)) then
    raise exception 'Uno de los platos se agotó. Quítalo del carrito para continuar.';
  end if;
  if s.plato_dia is null and exists (select 1 from jsonb_array_elements(p->'lines') l where l->>'dishId' = 'dia') then
    raise exception 'El menú del día ya no está disponible. Quítalo del carrito para continuar.';
  end if;

  insert into public.orders (customer_id, name, email, phone, origin, zone_id, zone_label, address, address_notes,
                             items, items_list, lines, subtotal, delivery, delivery_pending, total, pay)
  values (uid, trim(p->>'name'), v_email, coalesce(nullif(trim(p->>'phone'), ''), '—'), v_origin,
          case when v_origin = 'domicilio' then p->>'zone_id' end,
          case when v_origin = 'domicilio' then left(trim(p->>'zone_label'), 80) end,
          case when v_origin = 'domicilio' then trim(p->>'address') else 'Recoge en el local' end,
          case when v_origin = 'domicilio' then trim(coalesce(p->>'address_notes', '')) else '' end,
          p->>'items', p->'items_list', p->'lines', v_sub,
          v_delivery, coalesce(v_pending, false), v_sub + v_delivery, coalesce(p->>'pay', 'Efectivo (contra entrega)'))
  returning * into o;

  insert into public.order_messages (order_num, sender, body)
  values (o.num, 'dueno', 'Hemos recibido tu pedido. Si necesitas algo, puedes escribirnos por este chat. 🙌')
  returning id into m_id;
  update public.orders set client_seen_id = m_id, owner_seen_id = m_id where num = o.num returning * into o;
  return o;
end $$;

create or replace function public.advance_order(p_num bigint) returns public.orders
language plpgsql security definer set search_path = '' as $$
declare o public.orders; ns text;
begin
  if not public.is_owner() then raise exception 'Solo el dueño puede actualizar pedidos.' using errcode = '42501'; end if;
  select * into o from public.orders where num = p_num for update;
  if not found then raise exception 'Pedido no encontrado.'; end if;
  ns := public._next_status(o.status);
  if ns is null then return o; end if;
  update public.orders set status = ns where num = p_num returning * into o;
  insert into public.order_messages (order_num, sender, body) values (p_num, 'dueno', public._status_note(ns, o.origin));
  return o;
end $$;

create or replace function public.reject_order(p_num bigint, p_reason text) returns public.orders
language plpgsql security definer set search_path = '' as $$
declare o public.orders; r text := coalesce(nullif(left(trim(coalesce(p_reason, '')), 200), ''), 'Sin especificar');
begin
  if not public.is_owner() then raise exception 'Solo el dueño puede rechazar pedidos.' using errcode = '42501'; end if;
  select * into o from public.orders where num = p_num for update;
  if not found then raise exception 'Pedido no encontrado.'; end if;
  if o.status not in ('nuevo', 'aceptado') then raise exception 'Este pedido ya no se puede rechazar.'; end if;
  update public.orders set status = 'rechazado', reject_reason = r where num = p_num returning * into o;
  insert into public.order_messages (order_num, sender, body)
  values (p_num, 'dueno', 'Lamentamos informarte que no pudimos procesar tu pedido: ' || r || '. Acepta nuestras disculpas.');
  return o;
end $$;

create or replace function public.send_message(p_num bigint, p_body text) returns public.order_messages
language plpgsql security definer set search_path = '' as $$
declare m public.order_messages; side text; b text := trim(coalesce(p_body, ''));
begin
  if auth.uid() is null then raise exception 'No autenticado.' using errcode = '28000'; end if;
  if b = '' then raise exception 'Mensaje vacío.'; end if;
  if public.is_owner() then side := 'dueno';
  elsif exists (select 1 from public.orders where num = p_num and customer_id = auth.uid()) then side := 'cliente';
  else raise exception 'Pedido no encontrado.' using errcode = '42501';
  end if;
  insert into public.order_messages (order_num, sender, body) values (p_num, side, left(b, 1000)) returning * into m;
  if side = 'dueno' then update public.orders set owner_seen_id = m.id where num = p_num;
  else update public.orders set client_seen_id = m.id where num = p_num; end if;
  return m;
end $$;

create or replace function public.mark_seen(p_num bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare last_id bigint;
begin
  if auth.uid() is null then raise exception 'No autenticado.' using errcode = '28000'; end if;
  select coalesce(max(id), 0) into last_id from public.order_messages where order_num = p_num;
  if public.is_owner() then
    update public.orders set owner_seen_id = last_id where num = p_num and owner_seen_id < last_id;
  else
    update public.orders set client_seen_id = last_id where num = p_num and customer_id = auth.uid() and client_seen_id < last_id;
  end if;
end $$;

create or replace function public.set_review(p_num bigint, p_stars int default null, p_comment text default null, p_rated boolean default null)
returns public.orders
language plpgsql security definer set search_path = '' as $$
declare o public.orders;
begin
  update public.orders set
    review_stars = case when p_stars is null then review_stars else greatest(1, least(5, p_stars)) end,
    review_comment = case when p_comment is null then review_comment else nullif(left(trim(p_comment), 500), '') end,
    rated = rated or coalesce(p_rated, false)
  where num = p_num and customer_id = auth.uid()
  returning * into o;
  if not found then raise exception 'Pedido no encontrado.' using errcode = '42501'; end if;
  return o;
end $$;

-- Functions are executable by PUBLIC by default; only signed-in users may call the API ones.
revoke execute on function public.is_owner(), public._next_status(text), public._status_note(text, text),
  public.place_order(jsonb), public.advance_order(bigint), public.reject_order(bigint, text),
  public.send_message(bigint, text), public.mark_seen(bigint), public.set_review(bigint, int, text, boolean), public.touch_updated_at()
  from public, anon;
grant execute on function public.is_owner(), public.place_order(jsonb), public.advance_order(bigint),
  public.reject_order(bigint, text), public.send_message(bigint, text), public.mark_seen(bigint), public.set_review(bigint, int, text, boolean)
  to authenticated;

-- ----------------------------------------------------------------- barrios --
-- Each barrio is its own row: adding one, changing its price or removing it touches only that row,
-- so no phone saving other settings (even with an old copy or an old version) can undo it.
do $$
declare first_time boolean := to_regclass('public.zones') is null;
begin
  create table if not exists public.zones (
    id         text primary key check (char_length(id) between 1 and 60),
    label      text not null check (char_length(trim(label)) between 1 and 60),
    fee        integer not null default 0 check (fee between 0 and 1000000),
    ord        bigint generated always as identity,
    created_at timestamptz not null default now()
  );
  if first_time then
    -- 1. the list the panel had until now (kept inside the settings)
    insert into public.zones (id, label, fee)
    select z->>'id', left(trim(z->>'label'), 60), least(1000000, greatest(0, coalesce((z->>'fee')::numeric, 0)))::int
    from public.settings s,
         jsonb_array_elements(case when jsonb_typeof(s.desc_overrides->'__app'->'zones') = 'array'
                                   then s.desc_overrides->'__app'->'zones' else '[]'::jsonb end) with ordinality as e(z, i)
    where s.id = 1 and coalesce(z->>'id', '') <> '' and coalesce(trim(z->>'label'), '') <> ''
    order by i
    on conflict (id) do nothing;
    -- 2. never set up: the original list
    if not exists (select 1 from public.zones) then
      insert into public.zones (id, label, fee) values
      ('magnolia', 'La Magnolia', 0),
      ('alto_flores', 'Alto de las Flores', 8000),
      ('cumbres', 'Cumbres', 6000),
      ('milan', 'Milán', 5000),
      ('cometas', 'Las Cometas', 4000),
      ('rosellon', 'Rosellón', 6000),
      ('castelli', 'Castelli', 7000),
      ('obrero', 'El Obrero', 3000),
      ('naranjos', 'Los Naranjos', 2000),
      ('city_plaza', 'City Plaza', 7000),
      ('primavera', 'Primavera', 5000),
      ('san_rafael', 'San Rafael', 7000),
      ('cuenca', 'Cuenca', 8000),
      ('montiel', 'Jardines de Montiel', 6000),
      ('mina', 'La Mina', 7000),
      ('quintas_serrania', 'Quintas de la Serranía', 5000),
      ('quintas_zuniga', 'Quintas de Zúñiga', 4000),
      ('bosques_zuniga', 'Bosques de Zúñiga', 5000),
      ('barrio_mesa', 'Barrio Mesa', 5000),
      ('alcala', 'Alcalá', 6000),
      ('viva', 'Viva Envigado', 6000),
      ('terrazas', 'Terrazas del Río', 5000),
      ('california', 'California', 6000),
      ('mesa', 'Mesa', 5000),
      ('portal', 'El Portal', 5000),
      ('san_mateo', 'San Mateo', 2000),
      ('camino_verde', 'Camino Verde', 5000),
      ('viviendas_sur', 'Viviendas del Sur', 10000);
    end if;
    -- 3. barrios that orders were placed from but had been lost from the list (last name and price)
    insert into public.zones (id, label, fee)
    select id, label, fee from (
      select distinct on (lower(label)) id, label, fee, at from (
        select distinct on (o.zone_id) o.zone_id as id, left(trim(o.zone_label), 60) as label,
               least(1000000, greatest(0, o.delivery)) as fee, o.created_at as at
        from public.orders o
        where o.origin = 'domicilio' and o.zone_id is not null and o.zone_id <> 'otro' and coalesce(trim(o.zone_label), '') <> ''
        order by o.zone_id, o.created_at desc
      ) by_id
      order by lower(label), at desc
    ) used
    where not exists (select 1 from public.zones z where z.id = used.id or lower(z.label) = lower(used.label))
    order by at
    on conflict (id) do nothing;
  end if;
end $$;

